#!/usr/bin/env bash
# Writes src/oprf/__tests__/fixtures/oprf-wire-vectors.json: the wire bytes and
# Shamir combination the OPRF nodes' own Rust crates produce
# (scripts/oprf-wire-oracle), and BLAKE3 vectors from @noble/hashes
# (scripts/oprf-blake3-vectors.mjs).
#
#   scripts/generate-oprf-wire-vectors.sh          rewrite the fixture
#   scripts/generate-oprf-wire-vectors.sh --check  fail if it would change
#
# Needs: cargo (the crates are resolved offline from ~/.cargo/registry, so
# build proofport-oprf once first, or drop --offline), node, and this app's
# node_modules. The Rust build goes to a temporary target directory; nothing
# is written into the repository but the fixture.
set -euo pipefail
APP=$(git rev-parse --show-toplevel)
OUT="$APP/src/oprf/__tests__/fixtures/oprf-wire-vectors.json"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
command -v cargo >/dev/null || export PATH="$HOME/.cargo/bin:$PATH"
CARGO_TARGET_DIR="$TMP/target" cargo build --offline --release --quiet \
  --manifest-path "$APP/scripts/oprf-wire-oracle/Cargo.toml"
"$TMP/target/release/oprf-wire-oracle" > "$TMP/wire.json"
(cd "$APP" && node scripts/oprf-blake3-vectors.mjs) > "$TMP/blake3.json"
node -e '
const fs = require("fs");
const [wire, b3, out] = process.argv.slice(1);
const doc = {
  note: "Generated by scripts/generate-oprf-wire-vectors.sh. Do not edit.",
  wire: JSON.parse(fs.readFileSync(wire, "utf8")),
  blake3: JSON.parse(fs.readFileSync(b3, "utf8")),
};
fs.writeFileSync(out, JSON.stringify(doc, null, 2) + "\n");
' "$TMP/wire.json" "$TMP/blake3.json" "$TMP/out.json"
# The generated files must exist and be non-trivial: a tool that "succeeded"
# with nothing written is not a vector set.
node -e 'const d=require(process.argv[1]); if (d.wire.cases.length !== 3 || d.blake3.cases.length < 20) { console.error("vector set incomplete"); process.exit(1); }' "$TMP/out.json"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$TMP/out.json" "$OUT" || { echo "$OUT is out of date; run $0" >&2; exit 1; }
  echo "up to date: $OUT"
else
  cp "$TMP/out.json" "$OUT"
  echo "wrote $OUT"
fi
